    <section id="abonnement">
        <h2 class="font-headline-lg text-headline-lg text-on-surface">6. Abonnement et paiement</h2>

        <p class="mt-4">
            <strong>Seuls les prestataires paient</strong>, et ils paient SmartLink — jamais un
            client. C'est l'unique source de revenu de la plateforme.
        </p>

        <ul class="mt-4 list-disc space-y-1.5 pl-5">
            <li>Tout prestataire commence par <strong>trente jours d'essai gratuit</strong> au palier le plus complet.</li>
            <li>Passé l'essai, un palier payant se règle en Mobile Money. Une formule gratuite, plus limitée, reste disponible.</li>
            <li>Chaque paiement se valide sur le téléphone du prestataire. <strong>Il n'existe aucun prélèvement automatique</strong> : rien n'est débité sans cette validation.</li>
            <li>Un abonnement réglé couvre le nombre de jours annoncé au moment du paiement, à compter de celui-ci.</li>
            <li>Les prix et les plafonds de chaque palier sont affichés sur la page d'abonnement et peuvent évoluer ; un changement ne s'applique jamais à une période déjà réglée.</li>
        </ul>

        <p class="mt-4">
            À l'échéance, un abonnement non renouvelé expire : les services du prestataire sortent des
            recherches. <strong>Rien n'est supprimé</strong> — les demandes en cours, les
            conversations et les annonces restent accessibles depuis le compte, et reparaissent dès le
            renouvellement.
        </p>
        <p class="mt-3">
            Un abonnement réglé n'est pas remboursable au prorata, sauf indisponibilité prolongée du
            service imputable à SmartLink.
        </p>
    </section>

