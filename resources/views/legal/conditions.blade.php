    <section id="objet">
        <h2 class="font-headline-lg text-headline-lg text-on-surface">1. Objet du service</h2>

        <p class="mt-4">
            SmartLink met en relation des personnes qui cherchent un service de proximité au Cameroun
            — plomberie, électricité, coiffure, ménage, cours particuliers, et d'autres — avec des
            prestataires qui l'exercent.
        </p>
        <p class="mt-3">
            La plateforme publie des annonces, permet de chercher, d'envoyer une demande et
            d'échanger. Elle s'arrête là. Ce qui suit — le rendez-vous, la prestation, le prix, le
            règlement — se convient directement entre les deux personnes.
        </p>
    </section>

    <section id="mise-en-relation">
        <h2 class="font-headline-lg text-headline-lg text-on-surface">2. Mise en relation, pas transaction</h2>

        <div class="mt-4 rounded-xl border border-primary/30 bg-secondary-container/20 p-5">
            <p class="font-semibold text-on-surface">
                Aucune somme ne transite entre un client et un prestataire par SmartLink.
            </p>
            <p class="mt-2 text-on-surface-variant">
                Il n'y a ni panier, ni acompte, ni paiement en ligne de la prestation, ni commission
                prélevée. Le règlement se convient et s'effectue directement entre les deux parties,
                hors de la plateforme, par le moyen qu'elles choisissent.
            </p>
        </div>

        <p class="mt-4">
            Les prix affichés sur les annonces sont <strong>indicatifs</strong>. Ils donnent un ordre
            de grandeur ; ils n'engagent pas le prestataire et ne constituent pas une offre
            contractuelle. Le prix réel se discute au moment de la demande.
        </p>
        <p class="mt-3">
            SmartLink n'est ni partie au contrat de prestation, ni intermédiaire de paiement, ni
            garant de la bonne exécution. Il n'existe donc pas de « remboursement SmartLink » : la
            plateforme n'a jamais reçu l'argent de la prestation.
        </p>
    </section>

